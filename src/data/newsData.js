// Helper to generate URL-safe slug
export const generateSlug = (text) => {
  if (!text) return "news-" + Date.now();
  return text
    .toString()
    .toLowerCase()
    .trim()
    .replace(/[\s\W-]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .substring(0, 60) || "news-" + Date.now();
};

